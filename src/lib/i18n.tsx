let activeLanguage: NexusLanguage = "ru";

export function translate(value: string, language: NexusLanguage = activeLanguage): string {
  return language === "ru" ? (translations[value] ?? value) : value;
}

export const t = (value: string): string => translate(value);

function readLanguage(): NexusLanguage {
  try { return window.localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "ru"; }
  catch { return "ru"; }
}

interface LanguageContextValue { language: NexusLanguage; setLanguage: (language: NexusLanguage) => void; t: typeof translate; }
const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<NexusLanguage>(readLanguage);
  const setLanguage = useCallback((next: NexusLanguage) => {
    activeLanguage = next;
    setLanguageState(next);
    try { window.localStorage.setItem(STORAGE_KEY, next); } catch { /* Storage can be disabled; language still applies for this session. */ }
  }, []);
  useEffect(() => {
    activeLanguage = language;
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo(() => ({ language, setLanguage, t: translate }), [language, setLanguage]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error("useLanguage must be used inside LanguageProvider");
  return value;
}
